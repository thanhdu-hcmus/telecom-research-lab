skill(
    "ieee-paper-writing",
    "Use by paper_writer in approved P7 to write an IEEE draft from verified claims and grounded metadata.",
    """
Require G6. Read verified claims, model, limitations and grounded cards. Use journal
or conference IEEEtran template. Read [structure](references/structure.md) and
[citation workflow](references/citation-workflow.md). Cite only metadata-backed
entries generated by lab cite bib-from and checked by lab cite verify.
Use \\res{key} for every numeric result and numeric parameter in Abstract, Results
and Discussion; lab paper trace recomputes claims from manifest data. Never invent
citations, performance gains, significance or universal generalization. Unknown
results stay unstated. Source prose is paraphrased with citations, not copied.
Run build, trace and overlap; send only draft/artifacts to independent reviewer.
Respond to major findings; disclosure is drafted from real provenance and reviewed
by authors. Export only after all checks, including a clean-folder compile, pass.
""",
)
refs = {
    "structure.md": """# IEEE structure
Abstract: problem, mechanism, bounded verified result and scope. Introduction:
motivation, precise gap, evidence and limited contributions. Related Work:
mechanism-based synthesis and closest-work delta, no unsupported absence claim.
System Model: dimensions, units, assumptions, CSI/RIS/SIC and constraints.
Proposed Method: algorithm, guarantees/limitations and complexity. Analysis:
proved predictions with regimes. Results: protocol, fair baselines, intervals,
ablations/sensitivity, manifest-bound values/figures. Discussion: limitations and
untested settings. Conclusion: calibrated claims, no new numbers or citations.
""",
    "citation-workflow.md": """# Citation workflow
Never type a citation from memory. lab cite bib-from uses recorded source metadata.
lab cite verify checks every DOI/arXiv entry independently against primary APIs,
including title, authors, year and venue; all must pass. Retain receipts and exact
metadata provenance. Use IEEEtran bibliography style. Verify cited keys exist;
latexmk detects undefined references/citations. Source cards need page evidence.
""",
}
for name, text in refs.items():
    p = ROOT / ".agents/skills/ieee-paper-writing/references" / name
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text, encoding="utf-8", newline="\n")
